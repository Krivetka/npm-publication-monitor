// Writes documentation/database/schema.sql: the database structure as one DDL script.
// Reads a schema-only dump of a database built by the migrations from standard input:
//
//   pg_dump --schema-only --no-owner --no-privileges "$DATABASE_URL_ADMIN" | node scripts/db-schema.mjs
//
// The migrations stay the source of truth; this file is the same structure in one script,
// for a reader who wants the whole DDL in one place.

import { writeFile } from 'node:fs/promises';
import { text } from 'node:stream/consumers';

const HEADER = `-- npm-monitor: consolidated DDL script of the database structure (PostgreSQL 18).
--
-- Generated by pg_dump --schema-only from a database built by the migrations
-- (migrations/*.sql are the source of truth; this file is the same structure in one script).
-- It creates the tables, constraints, indexes, views, functions, triggers and comments, and
-- the journal partitions of the month of generation. Reference rows (table source) and the
-- feature catalogue are written by the migrations and by "npm run db:reference"; the roles
-- by deploy/db-roles.sql and the access rights by the function grant_app_privileges().
--
--   createdb npm_monitor && psql -d npm_monitor -v ON_ERROR_STOP=1 -f schema.sql
`;

const dump = await text(process.stdin);
// \restrict and \unrestrict are psql 17.6+ meta-commands with a random token: not part of the DDL.
const body = dump
  .split(/\r?\n/)
  .filter((l) => !l.startsWith('\\restrict ') && !l.startsWith('\\unrestrict '))
  .join('\n');
if (!body.includes('CREATE TABLE')) throw new Error('the input is not a schema dump');
await writeFile(new URL('../documentation/database/schema.sql', import.meta.url), `${HEADER}\n${body}`);
console.log(`schema.sql: ${body.split('\n').length} lines, ${(body.match(/^CREATE /gm) ?? []).length} CREATE statements`);
